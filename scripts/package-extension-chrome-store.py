#!/usr/bin/env python3
"""Zip apps/extension for Chrome Web Store upload (excludes store drafts / dist)."""
from __future__ import annotations

import json
import re
import zipfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "apps" / "extension"
OUT_DIR = SRC / "dist"
OUT = OUT_DIR / "gravitre-extension-chrome.zip"
SKIP_DIRS = {".git", "node_modules", "dist", "store", "__pycache__"}
SKIP_SUFFIXES = {".map", ".md"}
REGISTRY = REPO / "apps" / "web" / "lib" / "provider-registry.generated.json"
PROVIDERS_JS = SRC / "providers.js"


def _key(value: str) -> str:
    return re.sub(r"[^a-z0-9]", "", value.lower())


def write_providers() -> None:
    """Vendor marks for the popup and side panel, from the web app's provider registry.

    The logos themselves are served by gravitre.app, so the extension only carries
    the lookup (name, path, plates) and stays in step with the web app.
    """
    providers = json.loads(REGISTRY.read_text())["providers"]
    entries: dict[str, list] = {}
    lookup: dict[str, str] = {}
    for pid, p in sorted(providers.items()):
        if p.get("source") == "fallback" or not p.get("src"):
            continue
        entries[pid] = [
            p["name"],
            p["src"],
            p.get("srcDark") or p["src"],
            1 if p.get("lightPlate") else 0,
            1 if p.get("darkPlate") else 0,
        ]
        for name in [pid, p["name"], *p.get("aliases", [])]:
            lookup.setdefault(_key(name), pid)
    body = json.dumps({"entries": entries, "lookup": lookup}, separators=(",", ":"), sort_keys=True)
    PROVIDERS_JS.write_text(
        "/* Generated by scripts/package-extension-chrome-store.py from the web provider registry. Do not edit. */\n"
        f"const GV_PROVIDERS = {body}\n"
    )


def main() -> int:
    if not (SRC / "manifest.json").is_file():
        raise SystemExit("apps/extension/manifest.json missing")
    write_providers()
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    count = 0
    with zipfile.ZipFile(OUT, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for path in SRC.rglob("*"):
            if not path.is_file():
                continue
            rel = path.relative_to(SRC)
            if any(part in SKIP_DIRS for part in rel.parts):
                continue
            if path.suffix.lower() in SKIP_SUFFIXES and path.name != "README.md":
                # keep root README out of store zip; listing lives under store/
                continue
            if path.name == "README.md":
                continue
            zf.write(path, rel.as_posix())
            count += 1
    print(f"Wrote {OUT} ({count} files)")
    print("Upload in Chrome Developer Dashboard, then set NEXT_PUBLIC_CHROME_WEB_STORE_URL.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
